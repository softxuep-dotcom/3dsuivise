/*
 * 第一天 90 → 40 秒。
 *
 * Poki 实测 11 场会话时长中位数 **52 秒**，而入夜原本在第 90 秒 —— 也就是
 * **73% 的玩家从没见过夜**，而夜袭是这个游戏的全部。四条装备线、体温双向夹逼、
 * 井的回蓄、狗巢，全都住在他们看不到的地方。
 *
 * 40 而不是 35：出生点脚边就有 4 根枯木，捡 3 根 + 添柴实测要十几秒，
 * 再留一点给"囤水"那步，35 秒会把引导链压得没法完成。40 秒下中位玩家
 * 仍然能在离开前看到天黑。
 *
 * 这条只缩白天，第一昼夜因此从 240 秒降到 190 秒，
 * 而开局口粮是按 240 秒配的（见 STARTING_RATION 那段），所以只会更宽松，不会饿死人。
 *
 * ## 第一夜 150 → 100 → 150（改回来了）
 *
 * 当初改成 100 的理由留在下面，因为它看起来完全成立 —— 模拟层拿七种打法的画像
 * 各跑一遍，150 秒下**没有一种活到黎明，全部死于狗咬**（见 docs/游戏测试-交接.md）：
 *
 *     第一夜      黎明落在        活到黎明    整夜贴身次数
 *     150s        190s / 3m10s      1/6         3~5
 *     110s        150s / 2m30s      3/6         1~4
 *      90s        130s / 2m10s      5/6         1~4
 *
 * 而中位会话约 1m38s —— **绝大多数玩家从没完整走完一个昼夜循环**，
 * 而"熬过夜、天亮再来"正是这个游戏的核心。于是取 100 秒，把黎明提到 2m20s，
 * 压在中位玩家的耐心线之前。
 *
 * **2026-08-24：这条上线测过了，没有兑现，改回 150。**
 *
 * Poki Fit Test（8-23 12:03，包里确实含 100 秒）读 2m52s，1.0.28（150 秒）在
 * 8-22 13:25 读 3m12s。看着差 20 秒，但那张表有 **28 秒的时段效应**（清晨/深夜档
 * 均值 3m24s、中午档 2m56s，中午窗口内部还有 12 秒/小时的斜坡）。按钟点折算到
 * 同一时刻，两者都落在 172~176 秒 —— 没有差别。
 *
 * autoplay 那边更干脆：**活过第一夜在七种配置下全部是 55%** —— 夜长 100/150 ×
 * 攻营配额 4/5 × 野外石头 0/10，任意组合，一个百分点都不动。
 *
 * 机制上说得通。被咬死的中位时刻是 **1m37s**，而入夜在 0:40 —— 死在**入夜后第 57 秒**。
 * 从 150 砍到 100，砍掉的是时钟 2:20–3:10 那一段，那时候该死的早死光了。
 * 上面那张表量的是"活到黎明"，它把"夜更短所以终点更早"一并算了进去，
 * 于是看起来像存活率提升，其实**死亡时刻一秒没动**。这是个口径陷阱：
 * 要量第一夜难不难，得量死亡时刻，不能量"活到某个会跟着改的终点"。
 *
 * 改回 150 本地值 +10~14 秒（带石头 3m40s→3m50s，去石头 3m53s→4m07s）。
 * 第一夜救不了靠缩短 —— 要救得动**入夜后那 57 秒里发生的事**。
 */
