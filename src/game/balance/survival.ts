/**
 * 站定多久开始休息。5 → 4 → 3 秒。
 *
 * 这个门槛是"休息"这件事的全部成本 —— 它换来的是劳力和生命的快速回复，
 * 而战斗封锁（REST_COMBAT_LOCK = 6 秒）本来就挡住了"边打边回"。
 * 5 秒在实战里常常等不到：夜里几乎每 6 秒就会被摸一下，等于永远进不去。
 *
 * 降到 3 秒还有个手感上的理由：站定是移动端玩家**唯一放开摇杆的时刻**，
 * 门槛越高，手就被按得越久。文案里写死了这个秒数（hud.drain.hint，六个语言），
 * 改这里记得一起改。
 */
