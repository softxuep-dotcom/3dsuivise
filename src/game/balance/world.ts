// ============================================================================
// 五轴生存模型
//
//   体力(health)  恒定流失，是"该吃饭了"的硬心跳
//   劳力(stamina) 采集与攻击的预算，休息回得快、行动回得慢
//   体温(warmth)  白天有地板、夜晚有天花板 ⇒ 中暑只在白天、失温只在夜晚
//   水分(water)   归零立即死亡
//   饥饿(hunger)  归零立即死亡
//
// 基准版本昼夜周期 750 秒，我们是 240~255 秒，所以速率不是简单等比缩放，
// 而是按"在一个昼夜内应该发生几次危机"重新配平，偏离处见下方注释。
// ============================================================================

/**
 * 开局口粮。**这是新手能不能活过第一夜的分水岭**，不是送温暖。
 *
 * ## 为什么把饱食从 90 压到 40
 *
 * 上一版把初始值提到 90/85，于是这条课程表变成了：
 *
 *   饿死 214.3s · 渴死 202.4s · 第二个黎明 50 + 150 = **200s**
 *
 * 空着背包也能撑过第一夜 —— 口粮不再是门票。而更要命的是**时机**：
 * 1.1.33 实测平均每局只有约 143 秒（500 会话 / 3m3s / 约 1.28 局每会话）。
 * 也就是说"不吃会死"这一课安排在 214 秒，而观众 143 秒就散场了。
 * `r1/pack` 只有 55% —— 45% 的人整局没开过背包，因为游戏从没让他非开不可。
 *
 * **课不是讲得不好，是排在了散场之后。** 所以这一版把它提到台前：
 *
 *   饱食 40  →  预警（<{@link NEED_WARNING}）t=52.4s  ·  饿死 t=95.2s
 *
 * 52.4 秒卡在第一天（50 秒）刚结束的接缝上：`sim.fuelFirst` 那条"第一个白天
 * 目标行只说通关目标"的设计到点让位，需求提示才接手，两者不抢戏。
 * 而 95.2 秒稳稳落在 143 秒之内 —— 这一课终于讲得完。
 *
 * ## 为什么是 2 块熟肉而不是 1 块
 *
 * 两条需求轴都封顶 100，所以口粮值多少不只看给几份，更看**什么时候吃**。
 * 在预警线上吃一块（COOKED_HUNGER 是 26~38 的随机）：
 *
 *   饱食 18 → 44~56  →  再撑 105~133 秒，落在 157~185s，**仍然到不了 200s 的黎明**
 *
 * 一块不够是**故意的**：他会在夜里被警告第二次，再吃一次才过得去黎明。
 * 于是第一夜从"站着守火 150 秒"变成两次"注意到 → 处理掉"的闭环 ——
 * 这正是这一夜最缺的东西。两块都吃下去（70~94）就足够到黎明。
 *
 * ## 水分故意不动
 *
 * 水 85 → 预警 159.5s、渴死 202.4s，落在第二天。**饿肚子教第一夜、口渴教第二天。**
 * 两条轴同时告急只会让玩家觉得"这游戏在整我"，而不是学会两件事。
 * 代价是渴死线离黎明只剩 2.4 秒余量，所以水的脉冲提示同样要给（见 HudController）。
 *
 * 顺带逼他开一次背包 —— 那是吃、烤、造装备的总入口，不开就什么都学不会。
 *
 * 肉本身也会少量补水：生肉 +2~6，熟肉 +5~10；它只能缓冲水线，纯补水仍要靠水和仙人掌汁。
 */
export const STARTING_RATION: ReadonlyArray<readonly [InventoryItemKind, number]> = [
  ["water", 2],
  ["cooked-meat", 2],
  /*
   * 三根枯木。**这不是补给，是第一夜教学的道具。**
   *
   * 入夜那一段教学的第二拍是"走到火塘边点火"，而它是整段里唯一可能做不到的一拍 ——
   * 第一个白天只有 50 秒，捡一根柴要 30 劳力、还得先找到，玩家很可能天黑时两手空空。
   * 那时这一拍只能换成一句"白天要先捡枯木"然后跳过，等于最该教的那件事没教成。
   *
   * 1 → 2 的理由不是"再送一根"，是 1.1.31 那两个数：整局**攒到过 2 根柴**的
   * 只有 18%，而 sword-1 的料（皮×1 + 柴×2）**同时**齐过的只有 13% ——
   * 柴同时是唯一燃料和最便宜那件武器的造价，一份东西被两条链抢，结果是两条都断。
   * 玩家甚至没把地上那几根当成可捡的东西（第一天捡到柴的只有 9.6%）。
   * 直接把 wood2 这一级填平，让 equip|ready 退化成"打到一张皮"这一件事。
   *
   * 代价是明的：2 根烧得动 190 秒，够盖住 150 秒的第一夜 —— "火会在天亮前灭一次"
   * 这一课**确实松了**，但只松第一夜，而且是拿它换"玩家第一次真的造出一件装备"。
   * 想留住那一课就得逼他二选一：柴烧掉就造不了刀。那个选择本身比灭火更值得教。
   *
   * 2 → 3：上面那个"二选一"实测是**假选择** —— 2 根柴要么全烧要么全造刀，
   * 而两条链断哪条玩家都走不下去（第一夜冻死，或者整局没造出过装备）。
   * 第三根把这个死结解开：烧掉 2 根盖住第一夜，剩 1 根 + 白天再捡 1 根就能造刀。
   * 代价是第一夜的火现在有 285 秒余量、彻底烧不完，"火会灭"这一课留到第二夜去教
   * —— 那时白天有 180 秒，捡柴不再是奢侈品。
   */
  ["wood", 3],
];

